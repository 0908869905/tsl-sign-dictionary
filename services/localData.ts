interface TranscriptSegment {
  timeStr: string;
  seconds: number;
  text: string;
}

// Parse the raw text into structured data
const parseTranscript = (raw: string): TranscriptSegment[] => {
  const lines = raw.trim().split('\n');
  const segments: TranscriptSegment[] = [];
  
  let currentTimestamp: { str: string, sec: number } | null = null;

  lines.forEach(line => {
    const trimmed = line.trim();
    if (!trimmed) return;

    // Match "MM:SS" alone
    const timeOnlyMatch = trimmed.match(/^(\d+):(\d+)$/);
    
    // Match "MM:SS Text"
    const timeWithTextMatch = trimmed.match(/^(\d+):(\d+)\s+(.+)/);

    if (timeWithTextMatch) {
        const min = parseInt(timeWithTextMatch[1], 10);
        const sec = parseInt(timeWithTextMatch[2], 10);
        segments.push({
            timeStr: `${min}:${sec}`,
            seconds: min * 60 + sec,
            text: timeWithTextMatch[3].trim()
        });
        currentTimestamp = null;
    } else if (timeOnlyMatch) {
        const min = parseInt(timeOnlyMatch[1], 10);
        const sec = parseInt(timeOnlyMatch[2], 10);
        currentTimestamp = {
            str: `${min}:${sec}`,
            sec: min * 60 + sec
        };
    } else if (currentTimestamp) {
        // If we have a pending timestamp, this line is the text
        segments.push({
            timeStr: currentTimestamp.str,
            seconds: currentTimestamp.sec,
            text: trimmed
        });
        currentTimestamp = null;
    }
  });

  return segments;
};

